'use client';

import { useState } from 'react';
import { Download } from 'lucide-react';
import { apiFetchFile } from '@/services/api';
import { ImportType } from '@/types/api';
import { Button } from '@/components/ui/button';
import { downloadApiFile } from '@/lib/download';

export interface DownloadTemplateButtonProps {
  type: ImportType;
  /** Excel is the default; CSV stays available for other spreadsheet tools. */
  format?: 'xlsx' | 'csv';
  label?: string;
  variant?: 'primary' | 'outline' | 'ghost';
  size?: 'sm' | 'md' | 'lg';
}

/**
 * Downloads the sample import template. The workbook is generated by the API,
 * so the headers, instructions and examples always match the validator.
 */
export function DownloadTemplateButton({
  type,
  format = 'xlsx',
  label = format === 'csv' ? 'Download CSV template' : 'Download sample Excel template',
  variant = 'outline',
  size = 'sm',
}: DownloadTemplateButtonProps) {
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const download = async () => {
    setPending(true);
    setError(null);
    try {
      const file = await apiFetchFile(`/pharmacy/imports/templates/${type}?format=${format}`);
      downloadApiFile(file);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'Unable to download the template.');
    } finally {
      setPending(false);
    }
  };

  return (
    <div>
      <Button variant={variant} size={size} onClick={download} disabled={pending}>
        <Download className="mr-2 h-4 w-4" aria-hidden="true" />
        {pending ? 'Preparing…' : label}
      </Button>
      {error ? <p className="mt-1 text-xs text-danger">{error}</p> : null}
    </div>
  );
}
